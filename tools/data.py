def conn(ref, pos, pn, kind, cavities, term, term_qty, note=""):
    return dict(ref=ref, pos=pos, pn=pn, kind=kind, cavities=cavities, term=term, term_qty=term_qty, note=note)


def pin(ref, cav, wire, color, mm2, to, note=""):
    return dict(ref=ref, cav=cav, wire=wire, color=C.get(color, color), mm2=mm2, to=to, note=note)


