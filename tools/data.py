# ---------------------------------------------------------------- общий помощник для Y-адаптеров


def yad(a, b, cavs, tap_to, b_cav=lambda c: c):
    """Y-адаптер: разъём a (с врезками) и ответный b.
    cavs: [(полость a, провод a↔b, цвет, сечение, [(провод врезки, цвет, сечение), ...])]."""
    rows, mate = [], []
    for cav, w, c, s, taps in cavs:
        if w is None:
            rows.append(pin(a, cav, "—", "—", "", "не используется", "Пустая позиция"))
            continue
        rows.append(pin(a, cav, w, c, s, f"{b}:{b_cav(cav)}"))
        rows += [pin(a, cav, tw, tc, ts, tap_to) for tw, tc, ts in taps]
        mate.append(pin(b, b_cav(cav), w, c, s, f"{a}:{cav}"))
    return rows + sorted(mate, key=lambda r: str(r["cav"]))


def group(ref, wires, src="Y-адаптер"):
    return [pin(ref, "—", w, c, s, f"{src}, провод {w}" if src == "Y-адаптер" else src) for w, c, s in wires]


