-- Разовая классификация уже существующих проектов по МАСТЕР-ТЗ §6
-- (подтверждено владельцем): отечественные — всё под маркой LADA
-- (включая старое написание ВАЗ), остальное — иномарки. Марка — первое
-- слово названия (его всегда формирует и ручное создание, и агент:
-- "{Марка} {Модель} — проводка ТСУ"). Дальше это обычное редактируемое
-- поле — новые/изменённые проекты классифицируются тем же правилом в
-- коде (src/origin.ts), не в SQL.
UPDATE "Project"
SET "origin" = 'domestic'
WHERE "name" ILIKE 'Lada %' OR "name" ILIKE 'ВАЗ %';
