/**
 * Нормализация артикула для сравнения "одно и то же, записанное
 * по-разному" (пробелы/регистр/дефисы) — используется при проверке
 * дублей внутренних артикулов и артикулов поставщиков. Само значение
 * в БД хранится как ввёл пользователь, нормализация — только для
 * сравнения.
 */
export function normalizeArticle(raw: string): string {
  return raw
    .trim()
    .toUpperCase()
    .replace(/[\s_]+/g, "-")
    .replace(/-+/g, "-");
}
